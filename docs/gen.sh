#!/bin/sh
# Regenerates docs/stdlib.md from the compiler (squark doc std). The test suite fails if it is stale.
set -e
cd "$(dirname "$0")/.."
go build -o bin/squark ./cmd/squark
{
	echo "# squark standard library reference"
	echo
	echo "Generated by \`squark doc std\` (run \`docs/gen.sh\` to refresh). Signatures include reference"
	echo "provenance: \`-> T in p\` means a result may point into what \`p\` refers to, a parameter"
	echo "\`x T in p\` may be stored inside \`p\`, and \`in static\` means static memory only. Methods"
	echo "(\`fn T.name(...)\`) follow their type; \`-> T !\` means a result plus an error."
	echo
	echo '```squark'
	bin/squark doc std
	echo '```'
} > docs/stdlib.md
